"""Export fully resolved Python profiles for pip from the workspace lock."""
from pathlib import Path

from .wheelhouse import (NATIVE_PACKAGE, PRIVATE_WHEELS, PROFILES, export, inputs,
                         native_version, profile_requirements, require_platform, sha256)

DIRECTORY = Path('docker/python')


def requirements(profile):
    entries = profile_requirements(profile, export('--only-group', 'build'))
    private = PRIVATE_WHEELS if profile == 'pdfparse-full' else ()
    result = {'main': [], 'private': []}
    for name, requirement in sorted(entries.items()):
        pin = str(requirement.specifier)
        if name == NATIVE_PACKAGE:
            pin += '+' + native_version()
        result['private' if name in private else 'main'].append(name + pin)
    return result


def main():
    require_platform()
    DIRECTORY.mkdir(parents=True, exist_ok=True)
    for profile in PROFILES:
        for group, lines in requirements(profile).items():
            if group == 'main' or lines:
                suffix = '-private' if group == 'private' else ''
                (DIRECTORY / f'{profile}{suffix}.txt').write_text(
                    '# Generated by python -m scripts.docker.pins from uv.lock\n'
                    + '\n'.join(lines) + '\n')
    paths = sorted({name for profile in PROFILES for name in inputs(profile, Path.cwd())}
                   | {'scripts/docker/pins.py', 'scripts/docker/wheelhouse.py'}
                   | {str(path) for path in DIRECTORY.glob('*.txt')})
    (DIRECTORY / 'inputs.sha256').write_text(
        ''.join(f'{sha256(Path(path))}  {path}\n' for path in paths))


if __name__ == '__main__':
    main()
